CREATE DATABASE Corporate1;
USE Corporate1; 

CREATE TABLE EMPLOYEE (
    EMP_ID INT PRIMARY KEY,
    EMP_NAME VARCHAR(50),
    DESIGNATION VARCHAR(50),
    DEPARTMENT VARCHAR(50),
    SALARY DECIMAL(10, 2),
    HIRE_DATE DATE
);

