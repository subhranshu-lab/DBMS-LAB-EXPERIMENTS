CREATE DATABASE Corporate4;
USE Corporate4; 

CREATE TABLE DEPT (
    DEPTNO INT PRIMARY KEY,
    DNAME VARCHAR(50),
    LOC VARCHAR(50)
);

CREATE TABLE EMP (
    EMPNO INT PRIMARY KEY,
    ENAME VARCHAR(50),
    JOB VARCHAR(50),
    MGR INT,
    HIREDATE DATE,
    SAL DECIMAL(10,2),
    DEPTNO INT,
    CONSTRAINT FK_EMP_DEPT
    FOREIGN KEY (DEPTNO) REFERENCES DEPT(DEPTNO)
);

CREATE TABLE SALEGRADE (
    GRADE INT PRIMARY KEY,
    LOSAL DECIMAL(10,2),
    HISAL DECIMAL(10,2)
);

CREATE TABLE AREAS (
    AREAID INT PRIMARY KEY,
    AREA_NAME VARCHAR(50),
    DEPTNO INT,
    CONSTRAINT FK_AREAS_DEPT
    FOREIGN KEY (DEPTNO) REFERENCES DEPT(DEPTNO)
);

