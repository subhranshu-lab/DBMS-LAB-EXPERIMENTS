SELECT EMP_NAME, SALARY, (SALARY * 10 / 100) AS BONUS
FROM EMPLOYEE;

SELECT EMP_NAME, SALARY, SALARY - (SALARY * 10 / 100) AS SALARY_AFTER_TAX
FROM EMPLOYEE;

SELECT DEPARTMENT, COUNT(*) AS TOTAL_EMPLOYEE
FROM EMPLOYEE
GROUP BY DEPARTMENT;

